import { PLATFORM_PLAY_INTEGRITY, fromBase64 } from '@peage/protocol'
import {
  type PlayIntegrityTestKeys,
  type PlayIntegrityTokenHeaders,
  type PlayIntegrityVerdictParams,
  type PlayIntegrityVerdictPayload,
  createKeyAttestationRoot,
  createPlayIntegrityKeys,
  encryptPlayIntegrityVerdict,
  expiredCopyOf,
  issueKeyAttestationChain,
  keyIdFor,
  newDeviceKey,
  playIntegrityNonce,
  playIntegrityProof,
  playIntegrityVerdict,
  signPlayIntegrityVerdict,
} from '@peage/tests'
import { type KeyObject, X509Certificate } from 'node:crypto'
import { describe, expect, it } from 'vitest'

import { sha256 } from '../../bytes.ts'
import { resolvePlayIntegrityConfig } from '../config.ts'
import { revocationSerialOf } from '../revocationList.ts'
import { verifyPlayIntegrityAttestation } from '../verifyPlayIntegrityAttestation.ts'

const PACKAGE_NAME = 'dev.peage.specs'
const CHALLENGE = 'issued-challenge'
const keys = createPlayIntegrityKeys()
const root = createKeyAttestationRoot()
const NOT_REVOKED = new Set<string>()

const OPTIONS = resolvePlayIntegrityConfig({
  packageName: PACKAGE_NAME,
  decryptionKey: keys.decryptionKey,
  verificationKey: keys.verificationKey,
  keyAttestation: {
    trustedRoots: [root.certificate.toString()],
    loadRevokedSerialNumbers: async () => new Set(),
  },
})

function attestationChainFor(deviceKey: KeyObject, challenge = CHALLENGE): string[] {
  return issueKeyAttestationChain({
    root,
    publicKey: deviceKey,
    keyDescription: { attestationChallenge: sha256(challenge), packageName: PACKAGE_NAME },
  })
}

function buildAttestation(
  overrides: {
    deviceKey?: KeyObject
    nonce?: string
    verdict?: Partial<PlayIntegrityVerdictParams>
    /** Edit the verdict JSON before it's signed, for fields the builder doesn't expose. */
    editVerdict?: (verdict: PlayIntegrityVerdictPayload) => void
    /** Rewrite the signed verdict before it's encrypted. */
    editJws?: (jws: string) => string
    tokenKeys?: PlayIntegrityTestKeys
    headers?: PlayIntegrityTokenHeaders
    certificateChain?: string[]
  } = {},
) {
  const deviceKey = overrides.deviceKey ?? newDeviceKey()
  const certificateChain = overrides.certificateChain ?? attestationChainFor(deviceKey)
  const verdict = playIntegrityVerdict({
    packageName: PACKAGE_NAME,
    nonce: overrides.nonce ?? playIntegrityNonce(CHALLENGE, deviceKey),
    ...overrides.verdict,
  })
  overrides.editVerdict?.(verdict)
  const tokenKeys = overrides.tokenKeys ?? keys
  const jws = signPlayIntegrityVerdict(verdict, tokenKeys, overrides.headers?.jws)
  const token = encryptPlayIntegrityVerdict(
    overrides.editJws?.(jws) ?? jws,
    tokenKeys,
    overrides.headers?.jwe,
  )
  return {
    deviceKey,
    certificateChain,
    attestation: {
      challenge: CHALLENGE,
      keyId: keyIdFor(deviceKey),
      platform: PLATFORM_PLAY_INTEGRITY,
      proof: playIntegrityProof(token, certificateChain),
    },
  }
}

describe('verifyPlayIntegrityAttestation', () => {
  it("returns the device key and its chain's serial numbers for a valid attestation", () => {
    const { deviceKey, certificateChain, attestation } = buildAttestation()
    const registered = verifyPlayIntegrityAttestation(attestation, OPTIONS, NOT_REVOKED)
    expect(registered.publicKey.equals(deviceKey)).toBe(true)
    expect(registered.attestationCertificateSerialNumbers).toStrictEqual(
      certificateChain.map((der) => revocationSerialOf(new X509Certificate(fromBase64(der)))),
    )
  })

  it("stores the trusted root's serial, not the one of the root copy the device sent", () => {
    const deviceKey = newDeviceKey()
    const chain = attestationChainFor(deviceKey)
    const deviceRootCopy = expiredCopyOf(root).raw.toString('base64')
    const { attestation } = buildAttestation({
      deviceKey,
      certificateChain: [...chain.slice(0, -1), deviceRootCopy],
    })
    const registered = verifyPlayIntegrityAttestation(attestation, OPTIONS, NOT_REVOKED)
    expect(registered.attestationCertificateSerialNumbers?.at(-1)).toBe(
      revocationSerialOf(root.certificate),
    )
  })

  it('rejects a proof without a certificate chain', () => {
    const { attestation } = buildAttestation()
    const { integrityToken } = JSON.parse(new TextDecoder().decode(attestation.proof))
    const proof = new TextEncoder().encode(JSON.stringify({ integrityToken, publicKey: 'AA==' }))
    expect(() =>
      verifyPlayIntegrityAttestation({ ...attestation, proof }, OPTIONS, NOT_REVOKED),
    ).toThrow(/certificateChain is missing/)
  })

  it("rejects a key generated by a re-signed copy of the app, even with a genuine app's verdict", () => {
    const deviceKey = newDeviceKey()
    const resignedApp = issueKeyAttestationChain({
      root,
      publicKey: deviceKey,
      keyDescription: {
        attestationChallenge: sha256(CHALLENGE),
        packageName: PACKAGE_NAME,
        signingCertificateDigests: [sha256('attacker signing certificate')],
      },
    })
    const { attestation } = buildAttestation({ deviceKey, certificateChain: resignedApp })
    expect(() => verifyPlayIntegrityAttestation(attestation, OPTIONS, NOT_REVOKED)).toThrow(
      /different signing certificates/,
    )
  })

  it('rejects a verdict that names no signing certificate', () => {
    const { attestation } = buildAttestation({
      editVerdict: (verdict) => {
        delete verdict.appIntegrity.certificateSha256Digest
      },
    })
    expect(() => verifyPlayIntegrityAttestation(attestation, OPTIONS, NOT_REVOKED)).toThrow(
      /different signing certificates/,
    )
  })

  it('rejects a key attested for another challenge', () => {
    const deviceKey = newDeviceKey()
    const { attestation } = buildAttestation({
      deviceKey,
      certificateChain: attestationChainFor(deviceKey, 'another-challenge'),
    })
    expect(() => verifyPlayIntegrityAttestation(attestation, OPTIONS, NOT_REVOKED)).toThrow(
      /Key attestation challenge does not match/,
    )
  })

  it('rejects a key whose attestation chain contains a revoked certificate', () => {
    const { certificateChain, attestation } = buildAttestation()
    const intermediate = new X509Certificate(fromBase64(certificateChain[1] ?? ''))
    const revoked = new Set([revocationSerialOf(intermediate)])
    expect(() => verifyPlayIntegrityAttestation(attestation, OPTIONS, revoked)).toThrow(/revoked/)
  })

  it('rejects a proof that is not JSON', () => {
    const { attestation } = buildAttestation()
    const proof = new TextEncoder().encode('not json')
    expect(() =>
      verifyPlayIntegrityAttestation({ ...attestation, proof }, OPTIONS, NOT_REVOKED),
    ).toThrow(/not valid JSON/)
  })

  it('rejects a keyId that is not the hash of the submitted key', () => {
    const { attestation } = buildAttestation()
    const keyId = keyIdFor(newDeviceKey())
    expect(() =>
      verifyPlayIntegrityAttestation({ ...attestation, keyId }, OPTIONS, NOT_REVOKED),
    ).toThrow(/Key id does not match/)
  })

  it('rejects a token encrypted for a different app', () => {
    const { attestation } = buildAttestation({ tokenKeys: createPlayIntegrityKeys() })
    expect(() => verifyPlayIntegrityAttestation(attestation, OPTIONS, NOT_REVOKED)).toThrow(
      /not encrypted for the configured decryption key/,
    )
  })

  it('rejects a verdict not signed by the configured verification key', () => {
    const forger = createPlayIntegrityKeys()
    const { attestation } = buildAttestation({
      tokenKeys: { ...keys, signingKey: forger.signingKey },
    })
    expect(() => verifyPlayIntegrityAttestation(attestation, OPTIONS, NOT_REVOKED)).toThrow(
      /signature is invalid/,
    )
  })

  it('rejects a nonce bound to another challenge', () => {
    const deviceKey = newDeviceKey()
    const { attestation } = buildAttestation({
      deviceKey,
      nonce: playIntegrityNonce('another-challenge', deviceKey),
    })
    expect(() => verifyPlayIntegrityAttestation(attestation, OPTIONS, NOT_REVOKED)).toThrow(
      /nonce does not bind/,
    )
  })

  it('rejects a genuine verdict reused to register a different key', () => {
    const genuine = buildAttestation()
    const attackerKey = newDeviceKey()
    const { integrityToken } = JSON.parse(new TextDecoder().decode(genuine.attestation.proof))
    const attestation = {
      ...genuine.attestation,
      keyId: keyIdFor(attackerKey),
      proof: playIntegrityProof(integrityToken, attestationChainFor(attackerKey)),
    }
    expect(() => verifyPlayIntegrityAttestation(attestation, OPTIONS, NOT_REVOKED)).toThrow(
      /nonce does not bind/,
    )
  })

  it('rejects a verdict requested by another package', () => {
    const { attestation } = buildAttestation({
      editVerdict: (verdict) => {
        verdict.requestDetails.requestPackageName = 'com.other.app'
      },
    })
    expect(() => verifyPlayIntegrityAttestation(attestation, OPTIONS, NOT_REVOKED)).toThrow(
      /requested by a different package/,
    )
  })

  it('rejects a verdict older than ten minutes', () => {
    const { attestation } = buildAttestation({
      verdict: { timestampMillis: Date.now() - 11 * 60 * 1000 },
    })
    expect(() => verifyPlayIntegrityAttestation(attestation, OPTIONS, NOT_REVOKED)).toThrow(
      /too old/,
    )
  })

  it('rejects an app Play does not recognize by default', () => {
    const { attestation } = buildAttestation({
      verdict: { appRecognitionVerdict: 'UNRECOGNIZED_VERSION' },
    })
    expect(() => verifyPlayIntegrityAttestation(attestation, OPTIONS, NOT_REVOKED)).toThrow(
      /UNRECOGNIZED_VERSION/,
    )
  })

  it('accepts an app Play does not recognize with allowUnrecognizedApps, as development', () => {
    const { attestation } = buildAttestation({
      verdict: { appRecognitionVerdict: 'UNRECOGNIZED_VERSION' },
    })
    const attested = verifyPlayIntegrityAttestation(
      attestation,
      { ...OPTIONS, allowUnrecognizedApps: true },
      NOT_REVOKED,
    )
    expect(attested.environment).toBe('development')
  })

  it('rejects an unevaluated app even with allowUnrecognizedApps', () => {
    const { attestation } = buildAttestation({
      verdict: { appRecognitionVerdict: 'UNEVALUATED' },
    })
    expect(() =>
      verifyPlayIntegrityAttestation(
        attestation,
        { ...OPTIONS, allowUnrecognizedApps: true },
        NOT_REVOKED,
      ),
    ).toThrow(/UNEVALUATED/)
  })

  it('rejects a device that only meets basic integrity', () => {
    const { attestation } = buildAttestation({
      verdict: { deviceRecognitionVerdict: ['MEETS_BASIC_INTEGRITY'] },
    })
    expect(() => verifyPlayIntegrityAttestation(attestation, OPTIONS, NOT_REVOKED)).toThrow(
      /device integrity/,
    )
  })

  it('rejects a device with no integrity labels', () => {
    const { attestation } = buildAttestation({ verdict: { deviceRecognitionVerdict: [] } })
    expect(() => verifyPlayIntegrityAttestation(attestation, OPTIONS, NOT_REVOKED)).toThrow(
      /device integrity/,
    )
  })

  it('accepts a nonce sent with base64 padding, as Google samples do', () => {
    const deviceKey = newDeviceKey()
    const { attestation } = buildAttestation({
      deviceKey,
      nonce: `${playIntegrityNonce(CHALLENGE, deviceKey)}=`,
    })
    expect(() => verifyPlayIntegrityAttestation(attestation, OPTIONS, NOT_REVOKED)).not.toThrow()
  })

  it('rejects a verdict naming a different package in appIntegrity', () => {
    const { attestation } = buildAttestation({
      editVerdict: (verdict) => {
        verdict.appIntegrity.packageName = 'com.other.app'
      },
    })
    expect(() => verifyPlayIntegrityAttestation(attestation, OPTIONS, NOT_REVOKED)).toThrow(
      /names a different package/,
    )
  })

  it('rejects a recognized app verdict that does not name its package', () => {
    const { attestation } = buildAttestation({
      editVerdict: (verdict) => {
        delete verdict.appIntegrity.packageName
      },
    })
    expect(() => verifyPlayIntegrityAttestation(attestation, OPTIONS, NOT_REVOKED)).toThrow(
      /names a different package/,
    )
  })

  it('rejects a verdict whose app packageName is not a string', () => {
    const { attestation } = buildAttestation({
      editVerdict: (verdict) => {
        Object.assign(verdict.appIntegrity, { packageName: { name: PACKAGE_NAME } })
      },
    })
    expect(() => verifyPlayIntegrityAttestation(attestation, OPTIONS, NOT_REVOKED)).toThrow(
      /packageName is not a string/,
    )
  })

  it('rejects a verdict whose timestamp is not a number', () => {
    const { attestation } = buildAttestation({
      editVerdict: (verdict) => {
        verdict.requestDetails.timestampMillis = 'soon'
      },
    })
    expect(() => verifyPlayIntegrityAttestation(attestation, OPTIONS, NOT_REVOKED)).toThrow(
      /timestampMillis is not a number/,
    )
  })

  it('rejects a token using another JWE algorithm', () => {
    const { attestation } = buildAttestation({
      headers: { jwe: { alg: 'A128KW', enc: 'A256GCM' } },
    })
    expect(() => verifyPlayIntegrityAttestation(attestation, OPTIONS, NOT_REVOKED)).toThrow(
      /unexpected JWE algorithm/,
    )
  })

  it.each(['A128GCM', 'A256CBC-HS512'])(
    'rejects a token using the %s content encryption',
    (enc) => {
      const { attestation } = buildAttestation({ headers: { jwe: { alg: 'A256KW', enc } } })
      expect(() => verifyPlayIntegrityAttestation(attestation, OPTIONS, NOT_REVOKED)).toThrow(
        /unexpected JWE algorithm/,
      )
    },
  )

  it('rejects a verdict claiming an unsigned JWS algorithm', () => {
    const { attestation } = buildAttestation({ headers: { jws: { alg: 'none' } } })
    expect(() => verifyPlayIntegrityAttestation(attestation, OPTIONS, NOT_REVOKED)).toThrow(
      /unexpected JWS algorithm/,
    )
  })

  it('rejects a signed verdict with an extra segment', () => {
    const { attestation } = buildAttestation({ editJws: (jws) => `${jws}.AA` })
    expect(() => verifyPlayIntegrityAttestation(attestation, OPTIONS, NOT_REVOKED)).toThrow(
      /not a compact JWS/,
    )
  })

  it('rejects a verdict timestamped in the future', () => {
    const { attestation } = buildAttestation({
      verdict: { timestampMillis: Date.now() + 6 * 60 * 1000 },
    })
    expect(() => verifyPlayIntegrityAttestation(attestation, OPTIONS, NOT_REVOKED)).toThrow(
      /from the future/,
    )
  })

  it('rejects an oversized proof before decoding it', () => {
    const { attestation } = buildAttestation()
    const proof = new Uint8Array(17 * 1024)
    expect(() =>
      verifyPlayIntegrityAttestation({ ...attestation, proof }, OPTIONS, NOT_REVOKED),
    ).toThrow(/too large/)
  })

  describe('tampered tokens', () => {
    function withTokenParts(rewrite: (parts: string[]) => void) {
      const { certificateChain, attestation } = buildAttestation()
      const { integrityToken } = JSON.parse(new TextDecoder().decode(attestation.proof))
      const parts = integrityToken.split('.')
      rewrite(parts)
      return { ...attestation, proof: playIntegrityProof(parts.join('.'), certificateChain) }
    }

    it('rejects a token missing a segment', () => {
      const attestation = withTokenParts((parts) => parts.pop())
      expect(() => verifyPlayIntegrityAttestation(attestation, OPTIONS, NOT_REVOKED)).toThrow(
        /not a compact JWE/,
      )
    })

    it('rejects a token with an extra segment', () => {
      const attestation = withTokenParts((parts) => parts.push('AA'))
      expect(() => verifyPlayIntegrityAttestation(attestation, OPTIONS, NOT_REVOKED)).toThrow(
        /not a compact JWE/,
      )
    })

    it('rejects a token whose IV is not 12 bytes', () => {
      const attestation = withTokenParts((parts) => {
        parts[2] = Buffer.alloc(16).toString('base64url')
      })
      expect(() => verifyPlayIntegrityAttestation(attestation, OPTIONS, NOT_REVOKED)).toThrow(
        /malformed IV/,
      )
    })

    it('rejects a token whose authentication tag was altered', () => {
      const attestation = withTokenParts((parts) => {
        const tag = Buffer.from(parts[4] ?? '', 'base64url')
        tag.set([(tag[0] ?? 0) ^ 0xff], 0)
        parts[4] = tag.toString('base64url')
      })
      expect(() => verifyPlayIntegrityAttestation(attestation, OPTIONS, NOT_REVOKED)).toThrow(
        /failed authentication/,
      )
    })

    it.each([4, 12])('rejects a token whose authentication tag is cut to %i bytes', (length) => {
      const attestation = withTokenParts((parts) => {
        parts[4] = Buffer.from(parts[4] ?? '', 'base64url')
          .subarray(0, length)
          .toString('base64url')
      })
      expect(() => verifyPlayIntegrityAttestation(attestation, OPTIONS, NOT_REVOKED)).toThrow(
        /malformed authentication tag/,
      )
    })

    // Same algorithms, re-serialized header: only the GCM additional data changes.
    it('rejects a token whose protected header was re-encoded', () => {
      const attestation = withTokenParts((parts) => {
        parts[0] = Buffer.from(JSON.stringify({ enc: 'A256GCM', alg: 'A256KW' })).toString(
          'base64url',
        )
      })
      expect(() => verifyPlayIntegrityAttestation(attestation, OPTIONS, NOT_REVOKED)).toThrow(
        /failed authentication/,
      )
    })
  })
})
