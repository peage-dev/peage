#!/usr/bin/env bash
# Regenerates the static X.509 test fixtures used by the verifier specs, writing
# and formatting src/verifiers/ios/__tests__/certificateFixtures.ts in place:
#   bash packages/core/scripts/generate-cert-fixtures.sh
#
# Needs OpenSSL 3.x (not LibreSSL) for the custom-OID nonce extension. The
# certificates are throwaway; the 100-year validity is arbitrary.
set -euo pipefail

core_dir=$(CDPATH= cd "$(dirname "$0")/.." && pwd)
out="$core_dir/src/verifiers/ios/__tests__/certificateFixtures.ts"

work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT
cd "$work"
: > empty.ext
printf 'basicConstraints=critical,CA:TRUE\nkeyUsage=critical,keyCertSign\n' > ca.ext

key() { openssl ecparam -name prime256v1 -genkey -noout -out "$1.key"; }

self_signed() { # name subject
  key "$1"
  openssl req -x509 -new -key "$1.key" -subj "$2" -days 36500 -out "$1.crt"
}

issued_by() { # name issuer subject extfile
  key "$1"
  openssl req -new -key "$1.key" -subj "$3" -out "$1.csr"
  openssl x509 -req -in "$1.csr" -CA "$2.crt" -CAkey "$2.key" -CAcreateserial \
    -days 36500 -extfile "$4" -out "$1.crt"
}

base64_der() { openssl x509 -in "$1.crt" -outform DER | base64 | tr -d '\n'; }

self_signed root "/CN=Peage Test Root CA"
issued_by intermediate root "/CN=Peage Test Intermediate CA" ca.ext
issued_by leaf intermediate "/CN=Peage Test Leaf" empty.ext
issued_by rogue leaf "/CN=Peage Test Rogue Leaf" empty.ext

# nonce = SHA-256( authData(01 02 03 04) ‖ SHA-256("challenge") )
{ printf '\x01\x02\x03\x04'; printf challenge | openssl dgst -sha256 -binary; } \
  | openssl dgst -sha256 -binary | xxd -p -c 256 > nonce.hex
printf '1.2.840.113635.100.8.2 = DER:3024A1220420%s\n' "$(cat nonce.hex)" > nonce.ext
issued_by nonce_leaf intermediate "/CN=Peage Test Nonce Leaf" nonce.ext

self_signed unrelated_root "/CN=Peage Unrelated Root CA"

cat > "$out" <<EOF
// Generated by packages/core/scripts/generate-cert-fixtures.sh — do not edit by hand.
// Throwaway ECDSA P-256 certificates.
import { X509Certificate } from 'node:crypto'

const parse = (base64: string) => new X509Certificate(Buffer.from(base64, 'base64'))

/** Valid [leaf, intermediate, root] chain, each signed by the next. */
export const TEST_CHAIN: [X509Certificate, X509Certificate, X509Certificate] = [
  parse('$(base64_der leaf)'),
  parse('$(base64_der intermediate)'),
  parse('$(base64_der root)'),
]

/** Signed by TEST_CHAIN's leaf, which is not a CA. */
export const ROGUE_LEAF = parse('$(base64_der rogue)')

/** Self-signed root from a different chain; nothing in TEST_CHAIN links to it. */
export const UNRELATED_ROOT = parse('$(base64_der unrelated_root)')

/** The authData and challenge that NONCE_LEAF's nonce extension binds. */
export const NONCE_AUTH_DATA = Uint8Array.of(1, 2, 3, 4)
export const NONCE_CHALLENGE = 'challenge'

/** Leaf whose nonce extension binds SHA-256(NONCE_AUTH_DATA ‖ SHA-256(NONCE_CHALLENGE)). */
export const NONCE_LEAF = parse('$(base64_der nonce_leaf)')
EOF

(CDPATH= cd "$core_dir" && pnpm exec oxfmt "$out" >&2)
echo "Wrote and formatted $out" >&2
